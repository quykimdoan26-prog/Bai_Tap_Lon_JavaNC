IF DB_ID(N'ucop_db') IS NULL CREATE DATABASE ucop_db;
GO
USE ucop_db;
GO

CREATE TABLE [ROLE] (
    RoleID INT IDENTITY PRIMARY KEY,
    RoleName VARCHAR(50) NOT NULL UNIQUE,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE ACCOUNT (
    AccountID INT IDENTITY PRIMARY KEY,
    Username VARCHAR(50) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    Status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    RoleID INT NOT NULL REFERENCES [ROLE](RoleID),
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE ACCOUNT_PROFILE (
    AccountID INT PRIMARY KEY REFERENCES ACCOUNT(AccountID) ON DELETE CASCADE,
    FullName VARCHAR(100) NOT NULL, Email VARCHAR(100) UNIQUE, Phone VARCHAR(20),
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE CATEGORY (
    CategoryID INT IDENTITY PRIMARY KEY,
    ParentID INT NULL REFERENCES CATEGORY(CategoryID),
    CategoryName VARCHAR(100) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE ITEM (
    ItemID INT IDENTITY PRIMARY KEY,
    CategoryID INT NOT NULL REFERENCES CATEGORY(CategoryID),
    SKU VARCHAR(50) NOT NULL UNIQUE, Name VARCHAR(255) NOT NULL,
    BasePrice DECIMAL(18,2) NOT NULL, Weight DECIMAL(10,2) NOT NULL DEFAULT 0,
    Status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE WAREHOUSE (
    WarehouseID INT IDENTITY PRIMARY KEY,
    Code VARCHAR(50) NOT NULL UNIQUE, Name VARCHAR(100) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE STOCK_ITEM (
    StockItemID INT IDENTITY PRIMARY KEY,
    WarehouseID INT NOT NULL REFERENCES WAREHOUSE(WarehouseID),
    ItemID INT NOT NULL REFERENCES ITEM(ItemID),
    Quantity_OnHand INT NOT NULL DEFAULT 0, Quantity_Reserved INT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50),
    CONSTRAINT UQ_STOCK_ITEM UNIQUE (WarehouseID, ItemID)
);
CREATE TABLE PROMOTION (
    PromotionID INT IDENTITY PRIMARY KEY,
    Code VARCHAR(50) NOT NULL UNIQUE, DiscountType VARCHAR(20) NOT NULL,
    Value DECIMAL(18,2) NOT NULL, ExpiryDate DATETIME2 NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE [ORDER] (
    OrderID INT IDENTITY PRIMARY KEY,
    AccountID INT NOT NULL REFERENCES ACCOUNT(AccountID),
    PromotionID INT NULL REFERENCES PROMOTION(PromotionID),
    Status VARCHAR(50) NOT NULL DEFAULT 'CART',
    SubTotal DECIMAL(18,2) NOT NULL DEFAULT 0,
    DiscountAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    TaxAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    ShippingFee DECIMAL(18,2) NOT NULL DEFAULT 0,
    GrandTotal DECIMAL(18,2) NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE ORDER_ITEM (
    OrderItemID INT IDENTITY PRIMARY KEY,
    OrderID INT NOT NULL REFERENCES [ORDER](OrderID) ON DELETE CASCADE,
    ItemID INT NOT NULL REFERENCES ITEM(ItemID),
    Quantity INT NOT NULL CHECK (Quantity > 0),
    UnitPrice DECIMAL(18,2) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE PAYMENT (
    PaymentID INT IDENTITY PRIMARY KEY,
    OrderID INT NOT NULL REFERENCES [ORDER](OrderID) ON DELETE CASCADE,
    Method VARCHAR(50) NOT NULL, Amount DECIMAL(18,2) NOT NULL,
    Status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE SHIPMENT (
    ShipmentID INT IDENTITY PRIMARY KEY,
    OrderID INT NOT NULL REFERENCES [ORDER](OrderID) ON DELETE CASCADE,
    TrackingCode VARCHAR(100), Status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    DeliveryDate DATETIME2 NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CreatedBy VARCHAR(50), UpdatedBy VARCHAR(50)
);
CREATE TABLE PROMOTION_USAGE (
    UsageID INT IDENTITY PRIMARY KEY,
    PromotionID INT NOT NULL REFERENCES PROMOTION(PromotionID),
    AccountID INT NOT NULL REFERENCES ACCOUNT(AccountID),
    OrderID INT NOT NULL REFERENCES [ORDER](OrderID),
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME()
);
GO

